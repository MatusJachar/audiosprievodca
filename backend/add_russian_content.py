def main():
    print("\n" + "="*70)
    print("ADDING PROFESSIONAL RUSSIAN CONTENT")
    print("="*70)
    
    stops = list(tour_stops_collection.find().sort('stop_number', 1))
    
    for stop in stops:
        stop_num = stop['stop_number']
        stop_id = stop['_id']
        
        if stop_num in RUSSIAN_CONTENT:
            ru_data = RUSSIAN_CONTENT[stop_num]
            print(f"\nStop {stop_num}: {ru_data['title']}")
            print(f"  ✓ Adding Russian text...")
            
            tour_stops_collection.update_one(
                {'_id': stop_id},
                {'$set': {
                    'content.ru': {
                        'title': ru_data['title'],
                        'description': ru_data['description']
                    }
                }}
            )
            print(f"  ✓ Saved!")
    
    print("\n" + "="*70)
    print("RUSSIAN CONTENT COMPLETE!")
    print("="*70)
    
    # Verify
    print("\nVerification - Stop 1:")
    stop1 = tour_stops_collection.find_one({'stop_number': 1})
    print(f"  RU Title: {stop1['content']['ru']['title']}")
    print(f"  RU Desc: {stop1['content']['ru']['description'][:100]}...")
    print(f"  Has RU audio: {'ru' in stop1.get('audio', {})}")

if __name__ == "__main__":
    main()
